"""Benchmark the AST grammar engine on the grammar test suite and write EVALUATION_REPORT.md.

Run from backend/:
    venv/Scripts/python.exe scripts/evaluate_benchmarks.py [--runs 50] [--output EVALUATION_REPORT.md]

Exits non-zero if a case outside the known gaps fails, or if p95 latency misses the pipeline target.
"""

import argparse
import gc
import platform
import statistics
import sys
from datetime import datetime, timezone
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND_DIR))

import nltk  # noqa: E402

import grammar_engine  # noqa: E402
from tests.test_grammar import CASES  # noqa: E402

# End-to-end processing target from CLAUDE.md; the engine's own budget is grammar_engine.LATENCY_BUDGET_MS.
PIPELINE_TARGET_MS = 15.0
WARMUP_RUNS = 3


def percentile(sorted_values: list[float], fraction: float) -> float:
    return sorted_values[min(len(sorted_values) - 1, round(fraction * (len(sorted_values) - 1)))]


def evaluate(runs: int) -> dict:
    for _ in range(WARMUP_RUNS):
        for case in CASES:
            grammar_engine.translate(case.tokens)
    # Same heap treatment as main.py's startup, so timings match the served engine.
    gc.collect()
    gc.freeze()

    outputs: list[set[str]] = [set() for _ in CASES]
    latencies: list[list[float]] = [[] for _ in CASES]
    # Interleave cases across runs so machine noise spreads evenly instead of hitting one case.
    for _ in range(runs):
        for index, case in enumerate(CASES):
            result = grammar_engine.translate(case.tokens)
            outputs[index].add(result.formatted_text)
            latencies[index].append(result.latency_ms)

    rows = []
    for case, seen, samples in zip(CASES, outputs, latencies):
        output = next(iter(seen))
        rows.append({
            "case": case,
            "output": output,
            "passed": len(seen) == 1 and output == case.expected,
            "deterministic": len(seen) == 1,
            "median_ms": statistics.median(samples),
            "max_ms": max(samples),
        })
    all_samples = sorted(sample for samples in latencies for sample in samples)
    return {
        "rows": rows,
        "runs": runs,
        "samples": len(all_samples),
        "mean_ms": statistics.fmean(all_samples),
        "p50_ms": percentile(all_samples, 0.50),
        "p95_ms": percentile(all_samples, 0.95),
        "p99_ms": percentile(all_samples, 0.99),
        "max_ms": all_samples[-1],
        "over_budget": sum(sample >= grammar_engine.LATENCY_BUDGET_MS for sample in all_samples),
        "over_target": sum(sample >= PIPELINE_TARGET_MS for sample in all_samples),
        "slowest": max(rows, key=lambda row: row["median_ms"]),
    }


def verdict(value: float) -> str:
    engine_budget = grammar_engine.LATENCY_BUDGET_MS
    if value < engine_budget:
        return f"PASS (< {engine_budget:g} ms engine budget)"
    if value < PIPELINE_TARGET_MS:
        return f"PASS (< {PIPELINE_TARGET_MS:g} ms target, over {engine_budget:g} ms engine budget)"
    return f"FAIL (>= {PIPELINE_TARGET_MS:g} ms target)"


def fmt_tokens(tokens: list[str]) -> str:
    return f"`{' '.join(tokens)}`" if tokens else "*(empty)*"


def fmt_text(text: str) -> str:
    return text if text else '*""*'


def render_report(result: dict) -> str:
    rows = result["rows"]
    passed = sum(row["passed"] for row in rows)
    gaps = [row for row in rows if row["case"].known_gap]
    unexpected = [row for row in rows if not row["passed"] and not row["case"].known_gap]
    deterministic = all(row["deterministic"] for row in rows)
    engine_budget = grammar_engine.LATENCY_BUDGET_MS
    slowest = result["slowest"]
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines = [
        "# AST Grammar Engine Evaluation Report",
        "",
        f"Generated by `scripts/evaluate_benchmarks.py` on {generated} (Laptop 3 backend).",
        "",
        "## Summary",
        "",
        "| Metric | Result | Target |",
        "|---|---|---|",
        f"| Sentence transformation accuracy | {passed} / {len(rows)} ({passed / len(rows):.1%}) | all non-gap cases |",
        f"| Mean AST engine latency | {result['mean_ms']:.3f} ms | {verdict(result['mean_ms'])} |",
        f"| p50 latency | {result['p50_ms']:.3f} ms | {verdict(result['p50_ms'])} |",
        f"| p95 latency | {result['p95_ms']:.3f} ms | {verdict(result['p95_ms'])} |",
        f"| p99 latency | {result['p99_ms']:.3f} ms | {verdict(result['p99_ms'])} |",
        f"| Max latency | {result['max_ms']:.3f} ms | {verdict(result['max_ms'])} |",
        f"| Samples over {engine_budget:g} ms / {PIPELINE_TARGET_MS:g} ms | "
        f"{result['over_budget']} / {result['over_target']} of {result['samples']} | 0 over {PIPELINE_TARGET_MS:g} ms |",
        f"| Slowest case (median) | {slowest['median_ms']:.3f} ms, {fmt_tokens(slowest['case'].tokens)} | {verdict(slowest['median_ms'])} |",
        f"| Deterministic output | {'yes' if deterministic else 'NO'}, identical text across {result['runs']} runs per case | yes |",
        f"| Unexpected failures | {len(unexpected)} | 0 |",
        "",
        "Latency is the full engine call as returned in `executionLatencyMs`: normalization, lexing, NLTK CFG "
        "chart parsing, parse ranking, canonical AST rebuild and rendering. It is an upper bound on the CFG "
        "parse alone. No generative or predictive model is called on any path.",
        "",
        f"Targets: {PIPELINE_TARGET_MS:g} ms end-to-end processing (CLAUDE.md) and {engine_budget:g} ms for the "
        "grammar engine (`grammar_engine.LATENCY_BUDGET_MS`).",
        "",
        "## Method",
        "",
        f"- Cases: `tests/test_grammar.py::CASES` ({len(rows)} inputs covering SOV/OSV/VSO reordering, fillers, "
        "stutters, repetitions, contractions, pronoun case, agreement, do-support, zero copula, questions and fragments).",
        f"- {WARMUP_RUNS} warm-up passes, then {result['runs']} timed passes with cases interleaved "
        f"({result['samples']} samples).",
        "- `gc.collect()` + `gc.freeze()` before timing, matching the server's startup in `main.py`.",
        "",
        "## Environment",
        "",
        f"- Python {platform.python_version()} ({platform.python_implementation()}), NLTK {nltk.__version__}",
        f"- {platform.platform()}",
        f"- CPU: {platform.processor() or 'unknown'}",
        f"- Grammar: {len(grammar_engine.GRAMMAR.productions())} CFG productions, "
        f"parser `{type(grammar_engine.PARSER).__name__}`, chart edge budget {grammar_engine.MAX_CHART_EDGES}",
        "",
        "## Known gaps",
        "",
    ]
    if gaps:
        for row in gaps:
            lines.append(
                f"- {fmt_tokens(row['case'].tokens)}: expected \"{row['case'].expected}\", "
                f"got \"{row['output']}\" ({row['case'].known_gap})."
            )
    else:
        lines.append("- None.")
    if unexpected:
        lines += ["", "## Unexpected failures", ""]
        for row in unexpected:
            lines.append(
                f"- {fmt_tokens(row['case'].tokens)}: expected \"{row['case'].expected}\", got \"{row['output']}\"."
            )

    lines += [
        "",
        "## Per-case results",
        "",
        "| # | Input tokens | Expected | Output | Median ms | Max ms | Result |",
        "|---:|---|---|---|---:|---:|---|",
    ]
    for number, row in enumerate(rows, start=1):
        status = "pass" if row["passed"] else ("known gap" if row["case"].known_gap else "FAIL")
        lines.append(
            f"| {number} | {fmt_tokens(row['case'].tokens)} | {fmt_text(row['case'].expected)} | "
            f"{fmt_text(row['output'])} | {row['median_ms']:.3f} | {row['max_ms']:.3f} | {status} |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--runs", type=int, default=50, help="timed passes over the suite (default: 50)")
    parser.add_argument("--output", type=Path, default=BACKEND_DIR / "EVALUATION_REPORT.md")
    args = parser.parse_args()

    result = evaluate(args.runs)
    args.output.write_text(render_report(result), encoding="utf-8")

    rows = result["rows"]
    passed = sum(row["passed"] for row in rows)
    unexpected = [row for row in rows if not row["passed"] and not row["case"].known_gap]
    print(f"accuracy {passed}/{len(rows)} ({passed / len(rows):.1%}), unexpected failures: {len(unexpected)}")
    print(
        f"latency mean {result['mean_ms']:.3f} ms, p50 {result['p50_ms']:.3f}, p95 {result['p95_ms']:.3f}, "
        f"p99 {result['p99_ms']:.3f}, max {result['max_ms']:.3f} ({result['samples']} samples)"
    )
    print(f"report written to {args.output}")
    return 1 if unexpected or result["p95_ms"] >= PIPELINE_TARGET_MS else 0


if __name__ == "__main__":
    sys.exit(main())
